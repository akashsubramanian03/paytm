/**
 * A proof of income, derived from the ledger.
 *
 * This is deliberately not only a credit artifact. A gig worker asked for salary
 * slips by a landlord, a visa officer or a school has nothing to show — the
 * income is real, it simply never took the shape of a payslip. The same eighteen
 * months that produce a score can produce a document that says, verifiably,
 * "this person received a median of ₹X a month across N months from M distinct
 * payers."
 *
 * It states its own limits. It is derived from Paytm activity alone, so it
 * understates anyone paid partly in cash — and it says so, rather than letting a
 * reader assume it is complete.
 */
import prisma from '../../lib/db.js';
import { ACTOR, ARTIFACT_TYPE, DATA_TYPE, PURPOSE, SUBJECT_TYPE } from '../constants.js';
import { ENGINE_VERSION } from '../version.js';
import { requireConsent } from '../consent/consent.guard.js';
import * as audit from '../consent/audit.js';
import { extractLedgerFeatures } from '../features/ledger.features.js';
import { hashInputs } from '../util/hash.js';
import { medianInt, minInt, maxInt, sumInt } from '../util/stats.js';
import { monthsBetween, utcDayKey } from '../util/window.js';

export async function buildIncomeProof({ userId, user, asOf = new Date(), requestId, actorId }) {
  const token = await requireConsent({
    subjectType: SUBJECT_TYPE.USER,
    subjectId: userId,
    purpose: PURPOSE.UNDERWRITING,
    actor: ACTOR.USER,
    actorId: actorId ?? userId,
    requestId,
    asOf,
  });

  const ledger = await extractLedgerFeatures(userId, { asOf, token });
  const n = Math.max(ledger.activeMonths, 1);
  const inflows = ledger.monthlyInflowPaise.slice(-n);
  const earning = inflows.filter((v) => v > 0);

  const proof = {
    schemaVersion: 'nbk-income-1',
    subject: {
      name: `${user.firstName} ${user.lastName}`.trim(),
      // Enough to identify the holder to someone who already knows them, not
      // enough to be an identity document.
      maskedPhone: `${user.phone.slice(0, 2)}${'*'.repeat(6)}${user.phone.slice(-2)}`,
      accountOpenedAt: user.createdAt.toISOString(),
      accountAgeMonths: monthsBetween(user.createdAt, asOf),
    },
    period: {
      monthsObserved: n,
      monthsWithIncome: earning.length,
      from: utcDayKey(new Date(asOf.getTime() - n * 30 * 86_400_000)),
      to: utcDayKey(asOf),
    },
    income: {
      medianMonthlyPaise: medianInt(earning),
      lowestMonthPaise: minInt(earning),
      highestMonthPaise: maxInt(earning),
      totalReceivedPaise: sumInt(inflows),
      distinctPayers: ledger.distinctCounterparties,
      transactionCount: ledger.entryCount,
    },
    // The honest caveats, on the document itself rather than in a footnote
    // somebody has to go looking for.
    limitations: [
      'Derived from Paytm wallet activity only. Income received in cash or into another account is not visible here and is not included.',
      'This is a record of money received, not an employer’s declaration of salary.',
      'Simulated data. This document is generated by a demo and is not evidence of anything.',
    ],
    generatedAt: asOf.toISOString(),
    engineVersion: ENGINE_VERSION,
  };

  proof.verificationHash = hashInputs({ ...proof, generatedAt: utcDayKey(asOf) });

  await audit.logUse({
    token,
    dataTypes: [DATA_TYPE.WALLET_LEDGER],
    artifactType: ARTIFACT_TYPE.FINANCIAL_HEALTH_SCORE,
  });

  return proof;
}
